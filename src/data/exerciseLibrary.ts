/**
 * The next harder variation of a home exercise that isn't already in `exclude`
 * (e.g. Push-Up -> Decline Push-Up, or Archer Push-Up if Decline is already on the day).
 */
export function nextHarder(name: string, exclude: string[]): string | undefined {
  const taken = new Set(exclude.map((n) => n.toLowerCase()));
  let next = findLibraryExercise(name)?.harder;
  for (let i = 0; next && taken.has(next.toLowerCase()) && i < 5; i++) next = findLibraryExercise(next)?.harder;
  return next && !taken.has(next.toLowerCase()) ? next : undefined;
}

export function findLibraryExercise(name: string): LibraryExercise | undefined {
  const key = name.trim().toLowerCase();
  return EXERCISE_LIBRARY.find((e) => e.name.toLowerCase() === key);
}
